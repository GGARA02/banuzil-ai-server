def get_couple_classification(f_type: str, m_type: str) -> dict:
    """커플 결합 유형 조회"""
    return _COMBO_MAP.get(
        (f_type, m_type),
        {
            "label":   f"{f_type} × {m_type} 결합",
            "risk":    "불명확",
            "context": "",
            "f_desc":  f"[분류 미정] 여성 {f_type} (남성 파트너: {m_type})",
            "m_desc":  f"[분류 미정] 남성 {m_type} (여성 파트너: {f_type})",
        }
    )


def build_couple_profile(
    session_id: str,
    f_anxiety: float, f_avoidance: float, f_mbti: str, f_situation: str,
    m_anxiety: float, m_avoidance: float, m_mbti: str, m_situation: str,
) -> "CoupleProfile":
    from config.attachment_weight import CoupleProfile

    f_profile = build_attachment_profile(f_anxiety, f_avoidance)
    m_profile = build_attachment_profile(m_anxiety, m_avoidance)

    combo      = get_couple_classification(f_profile.attach_type, m_profile.attach_type)
    ipv_risk   = (f_profile.attach_type, m_profile.attach_type) in IPV_RISK_COMBOS
    guide      = build_intervention_guide(f_profile, m_profile)

    return CoupleProfile(
        session_id             = session_id,
        f_profile              = f_profile,
        m_profile              = m_profile,
        f_mbti                 = f_mbti.upper(),
        m_mbti                 = m_mbti.upper(),
        f_situation            = f_situation,
        m_situation            = m_situation,
        couple_combo           = f"{f_profile.attach_type} × {m_profile.attach_type}",
        classification         = combo["label"],
        classification_detail  = combo["context"],   # 공통 맥락
        f_classification_detail= combo["f_desc"],    # 여성 전용
        m_classification_detail= combo["m_desc"],    # 남성 전용
        intervention_guide     = guide,
        ipv_risk_flag          = ipv_risk,
    )
